/** Every language's copy. Missing keys in a language fall back to English. */
export const catalog: Record<Lang, Partial<Record<TemplateKey, string>>> = {
  en,
  hi,
  ...others,
} as Record<Lang, Partial<Record<TemplateKey, string>>>;

/** Replaces {placeholders}; unknown placeholders are left visible so mistakes are obvious in review. */
export function render(lang: Lang, key: TemplateKey, vars: Vars = {}): string {
  const template = catalog[lang][key] ?? en[key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

/** Lists the languages for the language menu, one per line, numbered in the order of LANGUAGES. */
export function languageMenu(codes: readonly Lang[] = LANGUAGES): string {
  return codes.map((lang, index) => `${index + 1}. ${LANGUAGE_NAMES[lang]}`).join('\n');
}

/** Devanagari script means the patient is writing in Hindi; otherwise use the fallback. Kept for callers that only need a guess. */
export function detectLang(text: string, fallback: Lang): Lang {
  return /[ऀ-ॿ]/.test(text) ? 'hi' : fallback;
}
